import fs from 'node:fs';

const [inputPath, outputPath, season = '2026', week = '1', draftGroupId = 'unknown'] = process.argv.slice(2);
if (!inputPath || !outputPath) {
  throw new Error('Usage: node scripts/build-draftkings-slate.mjs <draftables.json> <output.js> [season] [week] [draftGroupId]');
}

const payload = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
const primarySlot = { QB: 66, RB: 67, WR: 68, TE: 69, DST: 71 };
const rows = payload.draftables
  .filter((player) => primarySlot[player.position] === player.rosterSlotId)
  .map((player) => {
    const competition = player.competition || player.competitions?.[0] || {};
    const average = player.draftStatAttributes?.find((item) => item.id === 90)?.value;
    return {
      dkId: String(player.playerDkId || player.playerId || player.draftableId),
      name: player.displayName,
      position: player.position,
      team: player.teamAbbreviation,
      salary: Number(player.salary),
      avg: Number(average) || 0,
      game: competition.name || '',
      startTime: competition.startTime || '',
      status: player.status && player.status !== 'None' ? player.status : '',
    };
  })
  .sort((a, b) => b.salary - a.salary || a.position.localeCompare(b.position) || a.name.localeCompare(b.name));

const generatedAt = new Date().toISOString();
const output = `// Official DraftKings NFL Classic salaries. Generated by scripts/build-draftkings-slate.mjs.\n` +
  `// Draft group ${draftGroupId}; generated ${generatedAt}.\n` +
  `window.DK_NFL_SLATE = ${JSON.stringify({
    season: Number(season),
    week: Number(week),
    draftGroupId: Number(draftGroupId),
    generatedAt,
    players: rows,
  }, null, 2)};\n`;

fs.writeFileSync(outputPath, output);
console.log(`Wrote ${rows.length} DraftKings players to ${outputPath}`);
